import Foundation

/// Компактный bundled-список ЧАСТЫХ коротких (2-буквенных) слов — позитивный сигнал
/// для авто-конвертации коротких слов (3.1, issue #22 «Не могу» → «Yt могу»).
///
/// Зачем отдельный список, а не NSSpellChecker: на длине 2 системный словарь
/// принимает почти любой набор букв за «слово», поэтому обычная двусторонняя проверка
/// ненадёжна — ради этого в детекторе и стоял гейт `count >= 3`. Здесь мы разрешаем
/// ровно двухбуквенные слова, но ТОЛЬКО когда их конверсия попадает в этот выверенный
/// список частотных слов (строго позитивный сигнал, как у иврит-ветки детектора).
///
/// Безопасность (аудит раскладочных образов, scripts/audit_short.py):
///   • коллизий «частое ↔ частое» между ru и en НЕТ — образы 2-буквенных слов одной
///     раскладки не являются частотными словами другой;
///   • единичные «частое → шум/архаизм» (напр. архаичное en «ye» — образ ru «ну»)
///     решаются в пользу частотного слова: точность страдает лишь на словах, которые
///     в современном вводе практически не встречаются.
/// Список намеренно короткий и консервативный. Языки без списка сюда не попадают —
/// для них 2-буквенные слова, как и раньше, авто-путём не трогаются (нет регресса).
/// Слова только в нижнем регистре; сравнение — по `lowercased()`.
enum ShortWords {
    private static let ru: Set<String> = [
        "не", "ты", "на", "он", "мы", "вы", "да", "но", "за", "бы", "же", "из",
        "ну", "по", "то", "от", "их", "ее", "её", "со", "ли", "ни", "об", "ей",
        "во", "им", "ко", "те", "та", "уж", "ок", "эй",
    ]
    private static let en: Set<String> = [
        "to", "it", "of", "is", "in", "we", "me", "he", "my", "on", "do", "no",
        "be", "so", "go", "if", "up", "at", "as", "an", "us", "or", "by", "am",
        "ok", "hi", "oh", "ah", "um", "mr", "ya",
    ]

    /// Набор частотных коротких слов для языка (по 2-буквенному коду), либо nil,
    /// если для языка список не предусмотрен.
    static func common(_ lang: String) -> Set<String>? {
        switch String(lang.prefix(2)) {
        case "ru": return ru
        case "en": return en
        default:   return nil
        }
    }
}
